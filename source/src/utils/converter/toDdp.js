// 辅助类 Token（使用简单对象）
class Token {
  constructor(type, noteStr = '', note = '', octave = 0, halve = 0, duration = 1.0, index = 0) {
    this.type = type          // "note", "rest", "sustain", "barline"
    this.noteStr = noteStr    // 带HTML的显示字符串
    this.note = note          // 纯音符名（含升降号）
    this.octave = octave      // 八度偏移
    this.halve = halve        // 减时线数量
    this.duration = duration  // 时值（分数）
    this.index = index        // 序号
  }
}

/**
 * 简谱字符串转换为洞洞谱
 * @param {string} text 简谱字符串
 * @param {string} mode 指法模式
 * @param {string} tune 调性
 */
export function convertToDdp(text, mode, tune) {
  const result = {}
  let octaveNum = 0, halveNum = 0

  // 1. 获取 token
  const parts = text.split(/\s+/)
  let idx = 1
  const tokens = []

  for (const part of parts) {
    if (part === '') continue
    switch (part) {
      case '|':
        tokens.push(new Token('barline'))
        continue
      case '-':
        tokens.push(new Token('sustain'))
        continue
      case '0':
        tokens.push(new Token('rest', '0', '0', 0, 0, 1.0, idx++))
        continue
    }

    // 解析音符
    const firstChar = part.charAt(0)
    if (firstChar < '1' || firstChar > '7') {
      throw new Error('非法的输入内容：' + part)
    }

    let i = 1
    let octave = 0
    let halve = 0
    let point = ''          // 附点符号
    let numerator = 1
    let denominator = 1

    let semitoneSymbol = ''
    let semitoneStr = ''

    while (i < part.length) {
      const c = part.charAt(i)
      if (c === '\'') {
        octave++
      } else if (c === ',') {
        octave--
      } else if (c === '_') {
        semitoneStr = '<span style="position: absolute; left: -6px; top: -3px; font-size: 0.9em;">♭</span>'
        semitoneSymbol = 'b'
      } else if (c === '^') {
        semitoneStr = '<span style="position: absolute; left: -6px; top: -3px; font-size: 0.9em;">♯</span>'
        semitoneSymbol = '#'
      } else if (c === '.') {
        numerator = numerator * 2 + 1
        denominator = denominator * 2
        point += '·'
      } else if (c === '/') {
        denominator *= 2
        halve++
      }
      i++
    }

    const noteStr = semitoneStr + firstChar +
        '<span style="position: absolute">' + point + '</span>'
    const note = semitoneSymbol + firstChar
    const duration = numerator / denominator

    tokens.push(new Token('note', noteStr, note, octave, halve, duration, idx++))

    if (Math.abs(octave) > octaveNum) {
      octaveNum = Math.abs(octave)
    }
    if (halve > halveNum) {
      halveNum = halve
    }
  }

  // 2. 根据 token 生成前端洞洞谱渲染内容
  let renderStr = ''

  for (const token of tokens) {
    // 小节线
    if (token.type === 'barline') {
      renderStr += '<div class="score-item"><div class="barline"></div></div>'
      continue
    }

    let octave = 0, halve = 0, index = token.index
    let opacity = '0', noteStr = ''
    let fingering = [0, 0, 0, 0, 0]
    if (token.type === 'rest') {
      noteStr = '0'
    } else if (token.type === 'sustain') {
      noteStr = '—'
      index = 0
    } else {
      // 普通音符
      const noteKey = token.note + '_' + token.octave
      const currFingering = POSITION_MAP[mode]?.[noteKey]
      if (currFingering) {
        fingering = currFingering
        opacity = '1'
      } else {
        opacity = '0.25'
        // fingering 保持默认 [0,0,0,0,0]
      }
      octave = token.octave
      halve = token.halve
      noteStr = token.noteStr
    }

    // 容器开始
    renderStr += '<div class="score-item">'
    // 音符渲染盒子开始
    renderStr += '<div class="note-group note-idx-' + index + '">'

    // 1. 音符标签开始
    renderStr += '<div class="note-label">'
    // 1.1 高八度点
    for (let i = 1; i <= octaveNum; i++) {
      const opacityVal = (octaveNum - octave < i) ? 1 : 0
      renderStr += '<div class="octave-dot" style="opacity: ' + opacityVal + '">•</div>'
    }
    // 1.2 音符开始
    renderStr += '<div class="note-num">'
    renderStr += '<div>' + noteStr + '</div>'  // 数字
    // 减时线
    for (let i = 1; i <= halveNum; i++) {
      const opacityVal = (halve >= i) ? 1 : 0
      renderStr += '<div class="halve-line" style="opacity: ' + opacityVal + '"></div>'
    }
    renderStr += '</div>' // 音符结束
    // 1.3 低八度点
    for (let i = 1; i <= octaveNum; i++) {
      const opacityVal = (-octave >= i) ? 1 : 0
      renderStr += '<div class="octave-dot" style="opacity: ' + opacityVal + '">•</div>'
    }
    renderStr += '</div>' // 音符标签结束

    // 2. 笛子部分开始
    renderStr += '<div class="whistle" style="opacity: ' + opacity + '">'
    // 2.1 笛身开始
    renderStr += '<div class="whistle-body">'
    for (const val of fingering) {
      let closeClass = ''
      if (val === 1) closeClass = ' half-close'
      else if (val === 2) closeClass = ' close'
      renderStr += '<div class="hole' + closeClass + '"></div>'
    }
    renderStr += '</div>' // 笛身结束
    // 2.2 笛子超吹标记
    const overBlowCnt = mode === '5' ? octave + 1 : octave  // 指法5时octave可以为负值
    for (let i = 1; i <= 3; i++) {
      const opacityVal = overBlowCnt >= i ? 1 : 0
      renderStr += '<div class="whistle-octave" style="opacity: ' + opacityVal + '">＋</div>'
    }
    renderStr += '</div>' // 笛子部分结束

    renderStr += '</div>' // 音符渲染盒子结束
    renderStr += '</div>' // 容器结束
  }

  result.renderStr = renderStr

  // 3. 组装用于音乐播放的 events 数组
  const originFreqMap = FREQUENCIES[tune]?.[mode]
  if (!originFreqMap) {
    throw new Error('未找到调性 ' + tune + ' 模式 ' + mode + ' 的频率映射')
  }
  // 将复合键拆分为单键映射
  const freqMap = {}
  for (const [key, value] of Object.entries(originFreqMap)) {
    const keys = key.split(',')
    for (const k of keys) {
      freqMap[k.trim()] = value
    }
  }

  const events = []
  for (const token of tokens) {
    // 小节线跳过
    if (token.type === 'barline') continue

    // 延音线：延长前一个事件的拍数
    if (token.type === 'sustain' && events.length > 0) {
      const preEvent = events[events.length - 1]
      preEvent.beats += 1
    } else {
      const event = {
        beats: token.duration,
        type: token.type,
        note: token.note + '_' + token.octave,
        index: token.index,
        freq: freqMap[token.note + '_' + token.octave]
      }
      events.push(event)
    }
  }
  result.events = events

  return result
}